function algorithm(
  id: string,
  title: string,
  category: AlgorithmCategory,
  run: Runner,
  input: DaaInput,
  time: string,
  space: string,
  summary: string,
  correctness: string,
  derivation: string,
  example: string,
  pseudocode: string[],
  exercise: string,
  answer: string,
  constraints = 'Use the fields in the example input. Arrays contain at most 20 values; graphs at most 8 vertices; strings at most 32 UTF-16 code units. Optimization budgets are integers from 0 to 100.',
) {
  lessons.push({
    id,
    title,
    category,
    run,
    defaultInput: input,
    time,
    space,
    summary,
    correctness,
    derivation,
    example,
    pseudocode,
    exercise: { question: exercise, answer },
    constraints,
    extension: category === 'DAA Extensions',
  })
}

