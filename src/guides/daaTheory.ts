export function daaTheoryFor(module: AlgorithmModule) {
  const legacy = legacyStudy[module.id]
  const authored = specific[module.id] ?? structures[module.id]
  const learningTool = module.subcategory === 'Learning Tools'
  const toolProfile = profile(
    'Connect the current algorithm’s state, explanation and practice task. The summary and ordered actions below define this tool’s intended workflow.',
    'A workflow is consistent when explanations, predictions and saved results refer to the same algorithm and input snapshot. Learner progress is not proof that an algorithm or concept is fully covered.',
    'Separate the interface cost from the algorithm studied. Generating a trace scales with the underlying runner and retaining snapshots adds storage.',
    `For ${module.name}, identify the input and algorithm, follow the listed actions, then explain one step before revealing its answer. Check against the trace.`,
    'Many learning-tool pages demonstrate a workflow rather than a full assessment or execution service. Browser-local progress does not certify mastery.',
    'How do you verify a learning result?',
    'Explain the state change independently and test its invariant; distinguish an activity marker from demonstrated understanding.',
  )
  const base = authored ?? (learningTool ? toolProfile : categoryProfiles[module.category]) ?? categoryProfiles['Data Structures']
  const overview =
    module.id.includes('suite') ||
    (Boolean(suiteLinks[module.id]) && !legacy) ||
    learningTool ||
    (module.coverage === 'partial' && module.category !== 'Sorting' && module.category !== 'Searching' && module.category !== 'Games')
  return {
    ...base,
    idea: authored ? base.idea : `${module.summary} ${base.idea}`,
    proof: legacy?.proof ?? base.proof,
    analysis: legacy?.derivation ?? base.analysis,
    example: legacy?.example ?? base.example,
    limits: legacy?.constraints ?? base.limits,
    question: legacy?.question ?? base.question,
    answer: legacy?.answer ?? base.answer,
    code: legacy?.code ?? module.code,
    overview,
    related: suiteLinks[module.id] ?? (module.id === 'bfs-traversal' ? ['daa-bfs'] : module.id === 'dfs-traversal' ? ['daa-dfs'] : []),
    designSteps: module.pseudocode,
    method: module.subcategory ?? module.category,
    scope: overview
      ? 'Illustrative overview: explanations below describe the underlying methods; this demo does not implement every named algorithm.'
      : 'Algorithm lesson: distinguish the mathematical algorithm, this runner’s implementation and the stored visualization snapshots.',
  }
}
