test('queens checks predictions, highlights attacks, replays undo and browses every solution', async ({ page }) => {
  await page.goto('/#/backtracking/n-queens')
  await page.getByRole('button', { name: 'Visualization', exact: true }).click()
  const s = page.locator('.bt-studio')
  await s.getByLabel('Backtracking prediction', { exact: true }).fill('reject')
  await s.getByRole('button', { name: 'Check prediction', exact: true }).click()
  await expect(s.getByRole('status')).toContainText('Not yet')
  await s.getByLabel('Backtracking prediction', { exact: true }).fill('choose')
  await s.getByRole('button', { name: 'Check prediction', exact: true }).click()
  await expect(s.getByRole('status')).toContainText('Correct')
  await s.getByRole('button', { name: 'Reveal next decision', exact: true }).click()
  await expect(s.getByRole('button', { name: 'Row 0, column 0, queen', exact: true })).toBeVisible()
  await s.getByRole('button', { name: 'Next backtracking step', exact: true }).click()
  await expect(s.locator('.bt-candidate')).toHaveCount(1)
  await expect(s.locator('.bt-attacker')).toHaveCount(1)
  await s.getByRole('button', { name: 'Row 1, column 0, rejected candidate', exact: true }).click()
  await expect(s.locator('.ls-inspector')).toContainText('Square (1, 0)')
  const trace = executeLesson(lessonById.get('n-queens')!, { n: 4 }, 1500),
    undo = trace.steps.findIndex((step) => step.state?.backtrack?.phase === 'undo')
  await s.getByLabel('Backtracking timeline').press('Home')
  for (let i = 0; i < undo; i++) await s.getByLabel('Backtracking timeline').press('ArrowRight')
  await expect(s.locator('.bt-phase')).toHaveText('undo')
  await s.getByRole('button', { name: 'Inspect search node 1: r0 → c0', exact: true }).click()
  await expect(s.locator('.bt-decision h3')).toContainText('Step 2 of')
  await s.getByRole('button', { name: 'Inspect search node 0: Root', exact: true }).press('Enter')
  await expect(s.locator('.bt-decision h3')).toContainText('Step 1 of')
  await s.getByRole('button', { name: 'Show computed solutions', exact: true }).click()
  await expect(s.locator('.bt-solutions h3')).toHaveText('2 solution(s) found')
  await expect(s.locator('.bt-solution-path')).toContainText('[1, 3, 0, 2]')
  await s.getByRole('button', { name: 'Next solution', exact: true }).click()
  await expect(s.locator('.bt-solution-path')).toContainText('[2, 0, 3, 1]')
  await s.getByLabel('Backtracking Board size n').fill('9')
  await s.getByRole('button', { name: 'Run backtracking example', exact: true }).click()
  await expect(s.getByRole('alert')).toContainText('n ≤ 8')
  await expect(s.locator('.bt-solutions h3')).toHaveText('2 solution(s) found')
})

