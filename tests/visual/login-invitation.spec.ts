import { test, expect } from '@playwright/test'
test('optional login appears every second page and allows guest browsing', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('algodrishti-onboarded', 'true'))
  await page.goto('/#/sorting/bubble-sort')
  await expect(page.getByRole('region', { name: 'Optional login' })).toHaveCount(0)
  await page.evaluate(() => (location.hash = '/sorting/selection-sort'))
  const invite = page.getByRole('region', { name: 'Optional login' })
  await expect(invite).toBeVisible()
  await invite.getByRole('button', { name: 'Continue as guest' }).click()
  await expect(invite).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'Dataset', exact: true })).toBeVisible()
  await page.evaluate(() => (location.hash = '/sorting/insertion-sort'))
  await page.waitForTimeout(1100)
  await expect(invite).toHaveCount(0)
  await page.evaluate(() => (location.hash = '/searching/linear-search'))
  await expect(invite).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: `artifacts/login-invitation-${test.info().project.name}.png` })
  await invite.getByRole('button', { name: 'Log in to continue', exact: true }).click()
  await expect(page.locator('#account-dialog')).toBeVisible()
  const bounds = await page.locator('#account-dialog').boundingBox()
  expect(bounds!.width).toBeLessThanOrEqual(page.viewportSize()!.width)
  await page.locator('#account-close').click()
  await expect(page.locator('#account-dialog')).not.toBeVisible()
  await page.evaluate(() => window.dispatchEvent(new CustomEvent('aimer-account', { detail: { uid: 'test-user' } })))
  await page.evaluate(() => (location.hash = '/sorting/merge-sort'))
  await page.evaluate(() => (location.hash = '/sorting/quick-sort'))
  await page.waitForTimeout(1100)
  await expect(invite).toHaveCount(0)
})
