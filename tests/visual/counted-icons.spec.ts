import { test, expect } from '@playwright/test'
test('exact icon counts, character selection and moving swaps', async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('algodrishti-onboarded', 'true')
    localStorage.setItem('algodrishti-reduced-motion', 'false')
  })
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/#/sorting/bubble-sort')
  await page.getByRole('textbox', { name: 'Dataset', exact: true }).fill('79, 2')
  await page.getByRole('combobox', { name: 'Bar icons', exact: true }).selectOption('apples')
  await expect(page.locator('.studio-column[data-value="79"] [data-unit-icon]')).toHaveCount(79)
  await page.getByRole('combobox', { name: 'Bar icons', exact: true }).selectOption('dolphins')
  await expect(page.locator('.studio-column[data-value="79"] [data-unit-icon]')).toHaveCount(79)
  await expect(page.locator('.studio-column[data-value="79"]')).toContainText('🐬')
  for (let i = 0; i < 4; i++) await page.getByRole('button', { name: 'Step forward', exact: true }).click()
  await page.waitForTimeout(450)
  const before = await page.locator('.studio-column[data-value="79"]').boundingBox()
  await page.getByRole('button', { name: 'Step forward', exact: true }).click()
  await expect(page.locator('.studio-column[data-value="79"]')).toHaveAttribute('data-index', '1')
  await page.waitForTimeout(70)
  const during = await page.locator('.studio-column[data-value="79"]').boundingBox()
  await page.waitForTimeout(450)
  const after = await page.locator('.studio-column[data-value="79"]').boundingBox()
  expect(after!.x).toBeGreaterThan(before!.x)
  expect(during!.x).toBeLessThan(after!.x)
  await page.setViewportSize({ width: 390, height: 900 })
  await page.getByRole('textbox', { name: 'Dataset', exact: true }).fill('79, 18, 31, 9, 42')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.locator('.studio-visual').scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'artifacts/counted-dolphins-mobile.png' })
})
