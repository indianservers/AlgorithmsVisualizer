test('023 classifies problem versions and checks factor certificates using exact inputs', async ({ page }) => {
  await root(page).getByRole('radio', { name: 'TSP (Optimization: min tour)', exact: true }).click()
  await expect(root(page).locator('.cx-details>header .cx-badge')).toHaveText('NP-Hard')
  await expect(root(page).locator('.cx-details')).toContainText('not itself a yes/no language')
  await root(page).getByRole('radio', { name: 'Graph Connectivity', exact: true }).click()
  await expect(root(page).locator('.cx-details>header .cx-badge')).toHaveText('P')
  await root(page).getByRole('radio', { name: 'Integer Factorization (Decision)', exact: true }).click()
  await root(page).getByRole('button', { name: 'Check a factor', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('button', { name: 'Verify factor', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Valid')
  await dialog.getByLabel('Proposed factor d', { exact: true }).fill('13')
  await dialog.getByRole('button', { name: 'Verify factor', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Rejected')
  await dialog.getByLabel('Factor number N', { exact: true }).fill(String((1n << 200n) + 2n))
  await dialog.getByLabel('Factor threshold k', { exact: true }).fill('2')
  await dialog.getByLabel('Proposed factor d', { exact: true }).fill('2')
  await dialog.getByRole('button', { name: 'Verify factor', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Valid')
})
test('023 distinguishes a failed SAT witness from unsatisfiability and validates edited formulas', async ({ page }) => {
  await root(page).getByRole('button', { name: 'Toggle SAT variable x3', exact: true }).click()
  await expect(root(page).locator('.cx-certificate-result')).toContainText('Rejected certificate')
  await expect(root(page).locator('.cx-certificate-content')).toContainText('does not prove the formula unsatisfiable')
  await root(page).getByRole('button', { name: 'Toggle SAT variable x1', exact: true }).click()
  await expect(root(page).locator('.cx-certificate-result')).toContainText('Valid certificate')
  const dialog = await editor(page)
  await dialog.getByLabel('Certificate instance input', { exact: true }).fill('0')
  await dialog.getByRole('button', { name: 'Apply certificate example', exact: true }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await dialog.getByLabel('Certificate instance input', { exact: true }).fill('1;-1')
  await dialog.getByRole('button', { name: 'Apply certificate example', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(root(page).locator('.cx-certificate-result')).toContainText('Rejected certificate')
  await root(page).locator('.mom-tabs').getByRole('button', { name: 'Experiments', exact: true }).click()
  await root(page)
    .getByRole('button', { name: /Find SAT witness/ })
    .click()
  await expect(root(page).getByRole('status')).toContainText('2')
  await expect(root(page).getByRole('status')).toContainText('unsatisfiable')
})
