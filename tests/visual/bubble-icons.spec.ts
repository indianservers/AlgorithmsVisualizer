import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('algodrishti-onboarded', 'true')
    localStorage.setItem('algodrishti-reduced-motion', 'true')
    localStorage.setItem('algodrishti-input', '42,18,67,9,31,73,54,26,88,12')
    localStorage.removeItem('algodrishti-bubble-view')
  })
})

test('bubble-only switch preserves snapshots, scales penguins and sorts accurately', async ({ page }) => {
  await page.goto('/#/sorting/bubble-sort')
  await page.getByRole('button', { name: 'Visualization', exact: true }).click()
  await expect(page.locator('.bar-stage')).toBeVisible()
  await page.getByRole('button', { name: 'Icons', exact: true }).click()
  const slots = page.locator('.penguin-slot')
  await expect(slots).toHaveCount(10)
  expect(await slots.nth(8).locator('svg').getAttribute('height')).not.toBe(await slots.nth(3).locator('svg').getAttribute('height'))
  const height = async (i: number) => Number(await slots.nth(i).locator('svg').getAttribute('height'))
  expect(await height(8)).toBeGreaterThan(await height(3))
  await expect(slots.nth(0).locator('.penguin-value')).toHaveText('42')
  await page.getByRole('button', { name: 'Step forward', exact: true }).click()
  await expect(slots.nth(0)).toHaveAttribute('data-value', '18')
  const metrics = await page.locator('.metrics-panel').textContent()
  await page.getByText('Playback options', { exact: true }).click()
  await page.locator('.speed input').press('End')
  await page.getByRole('button', { name: 'Sort', exact: true }).click()
  await page.getByRole('button', { name: 'Bars', exact: true }).click()
  await page.getByRole('button', { name: 'Icons', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Pause', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Stop', exact: true }).click()
  expect(await page.locator('.metrics-panel').textContent()).toBe(metrics)
  await expect(slots.nth(1)).toHaveAttribute('data-status', 'swapping')
  await page.getByRole('button', { name: 'Bars', exact: true }).click()
  await page.getByRole('button', { name: 'Icons', exact: true }).click()
  await expect(slots.nth(0)).toHaveAttribute('data-value', '18')
  await page.getByRole('button', { name: 'Step backward', exact: true }).click()
  await expect(slots.nth(0)).toHaveAttribute('data-value', '42')
  await page.getByRole('button', { name: 'Jump to last step', exact: true }).click()
  expect(await slots.evaluateAll((nodes) => nodes.map((n) => Number(n.getAttribute('data-value'))))).toEqual([9, 12, 18, 26, 31, 42, 54, 67, 73, 88])
  await expect(page.locator('.penguin-slot.sorted')).toHaveCount(10)
  await page.goto('/#/sorting/selection-sort')
  await page.getByRole('button', { name: 'Visualization', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Icons', exact: true })).toHaveCount(1)
  await page.getByRole('button', { name: 'Bars', exact: true }).click()
  await expect(page.locator('.bar-stage')).toBeVisible()
  await expect(page.locator('.bubble-compact')).toHaveCount(0)
})

test('compact panel retains presets and signed/zero/equal value labels', async ({ page }) => {
  await page.goto('/#/sorting/bubble-sort')
  await page.getByRole('button', { name: 'Visualization', exact: true }).click()
  await page.getByRole('button', { name: 'Icons', exact: true }).click()
  await page.getByLabel('Array (comma separated)').fill('-5, 0, 5, 5')
  await expect(page.locator('.penguin-slot')).toHaveCount(4)
  expect(await page.locator('.penguin-value').allTextContents()).toEqual(['-5', '0', '5', '5'])
  const heights = await page.locator('.penguin-art').evaluateAll((nodes) => nodes.map((n) => Number(n.getAttribute('height'))))
  expect(heights[0]).toBeLessThan(heights[1])
  expect(heights[1]).toBeLessThan(heights[2])
  expect(heights[2]).toBe(heights[3])
  await page.getByLabel('More input presets').selectOption('all-equal')
  const equal = await page.locator('.penguin-art').evaluateAll((nodes) => nodes.map((n) => n.getAttribute('height')))
  expect(new Set(equal).size).toBe(1)
  await page.getByLabel('More input presets').selectOption('single')
  await expect(page.locator('.penguin-slot')).toHaveCount(1)
  await page.getByRole('button', { name: 'Clear', exact: true }).click()
  await expect(page.locator('.penguin-slot')).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})

